//! Docker-style friendly machine names: `<adjective>_<scientist>`, e.g.
//! `boring_wozniak`. A large dictionary (~200 × ~260 ≈ 52k combinations);
//! callers pick a *unique* one via [`unique_name`].

use std::io::Read;
use std::sync::Mutex;

/// One-shot override for the next machine name — `start <id>` sets this so an
/// in-place restart keeps the machine's original name. Consumed by the boot path.
static NAME_OVERRIDE: Mutex<Option<String>> = Mutex::new(None);

/// Force the next generated name (once) — used by restart to preserve the name.
pub fn set_override(name: &str) {
    *NAME_OVERRIDE.lock().unwrap() = Some(name.to_string());
}

/// Take a pending name override, if any.
pub fn take_override() -> Option<String> {
    NAME_OVERRIDE.lock().unwrap().take()
}

