/// One random `adjective_scientist` name (no uniqueness guarantee).
pub fn random_name() -> String {
    let mut buf = [0u8; 8];
    let _ = std::fs::File::open("/dev/urandom").and_then(|mut f| f.read_exact(&mut buf));
    let r = u64::from_le_bytes(buf) as usize;
    let a = ADJECTIVES[r % ADJECTIVES.len()];
    let n = NAMES[(r / ADJECTIVES.len()) % NAMES.len()];
    format!("{a}_{n}")
}

/// A **unique** name: draws random candidates, using `taken` to reject
/// collisions. After many misses (a nearly-full space) it appends a short hex
/// suffix so a name is always produced.
pub fn unique_name(mut taken: impl FnMut(&str) -> bool) -> String {
    for _ in 0..64 {
        let candidate = random_name();
        if !taken(&candidate) {
            return candidate;
        }
    }
    // Space is saturated — guarantee uniqueness with a numeric suffix.
    for _ in 0..64 {
        let mut buf = [0u8; 2];
        let _ = std::fs::File::open("/dev/urandom").and_then(|mut f| f.read_exact(&mut buf));
        let candidate = format!("{}_{:04x}", random_name(), u16::from_le_bytes(buf));
        if !taken(&candidate) {
            return candidate;
        }
    }
    random_name()
}
